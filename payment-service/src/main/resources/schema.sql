CREATE TABLE IF NOT EXISTS users (
    id bigint PRIMARY KEY,
    name text NOT NULL
);
CREATE TABLE IF NOT EXISTS accounts (
    id bigint GENERATED BY DEFAULT AS IDENTITY (START WITH 100) PRIMARY KEY,
    user_id bigint NOT NULL REFERENCES users(id),
    balance bigint NOT NULL CHECK (balance >= 0)
);
CREATE TABLE IF NOT EXISTS payments (
    id uuid PRIMARY KEY,
    sender bigint NOT NULL REFERENCES accounts(id),
    recipient bigint NOT NULL REFERENCES accounts(id),
    amount bigint NOT NULL CHECK (amount > 0),
    request_key varchar(128) NOT NULL,
    status text NOT NULL CHECK (status IN ('SUCCEEDED', 'DECLINED')),
    UNIQUE (sender, request_key),
    CHECK (sender <> recipient)
);
